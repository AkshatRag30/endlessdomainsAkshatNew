// One off fixture generator (bulk listing v2 plan, phase 2, question V1).
// Uses Seaport.js's own bulk order code as the reference implementation.
// Usage: node make-bulk-fixtures.js <seaportjs-env dir> <output json>
const path = require('path')
const fs = require('fs')

const envDir = process.argv[2]
const outFile = process.argv[3]
const mod = (p) => require(path.join(envDir, 'node_modules', p))
const { Wallet, id, Signature, TypedDataEncoder, keccak256, toUtf8Bytes } = mod('ethers')
const { getBulkOrderTree } = mod('@opensea/seaport-js/lib/utils/eip712/bulk-orders.js')
const seaportjsVersion = mod('@opensea/seaport-js/package.json').version

const CHAIN_ID = 137
const SEAPORT = '0x0000000000000068F116a894984e2DB1123eB395'
const USDT = '0xc2132D05D31c914a87C6611C10748AEb04B58e8F'
const DOMAIN_NFT = '0xa9a6A3626993D487d2Dbda3173cf58cA1a9D9e9f'
const FEE_RECIPIENT = '0x' + 'cd'.repeat(20)
const START = 1_800_000_000
// Test only key, derived from a phrase so no raw key sits in the repo. The test derives it the same way.
const KEY_PHRASE = 'endless bulk order tree fixture signer'
const wallet = new Wallet(id(KEY_PHRASE))
const domain = { name: 'Seaport', version: '1.6', chainId: CHAIN_ID, verifyingContract: SEAPORT }

function order(i) {
  const total = 1_000_000n * BigInt(i + 1) // i + 1 USDT, 6 decimals
  const fee = (total * 250n) / 10000n
  return {
    offerer: wallet.address,
    zone: '0x0000000000000000000000000000000000000000',
    offer: [{ itemType: 2, token: DOMAIN_NFT, identifierOrCriteria: String(1000 + i), startAmount: '1', endAmount: '1' }],
    consideration: [
      { itemType: 1, token: USDT, identifierOrCriteria: '0', startAmount: String(total - fee), endAmount: String(total - fee), recipient: wallet.address },
      { itemType: 1, token: USDT, identifierOrCriteria: '0', startAmount: String(fee), endAmount: String(fee), recipient: FEE_RECIPIENT },
    ],
    orderType: 0,
    startTime: String(START),
    endTime: String(START + 7 * 24 * 3600),
    zoneHash: '0x' + '00'.repeat(32),
    salt: String(424242 + i),
    conduitKey: '0x' + '00'.repeat(32),
    counter: '0',
  }
}

async function makeCase(n) {
  const orders = Array.from({ length: n }, (_, i) => order(i))
  const tree = getBulkOrderTree(orders)
  const value = { tree: tree.getDataToSign() }
  // Same steps as Seaport.js signBulkOrder: sign, compact to 64 bytes (EIP 2098), then encode proof per order.
  const walletSignature = await wallet.signTypedData(domain, tree.types, value)
  const compact = Signature.from(walletSignature).compactSerialized
  return {
    count: n,
    height: tree.depth,
    bulkOrderType: tree.types.BulkOrder[0].type,
    // The real EIP712 type hash of BulkOrder. Not Seaport.js getBulkOrderTypeHash, which hashes only the field type text.
    typeHash: keccak256(toUtf8Bytes(TypedDataEncoder.from(tree.types).encodeType('BulkOrder'))),
    root: tree.root,
    digest: TypedDataEncoder.hash(domain, tree.types, value),
    walletSignature,
    compactSignature: compact,
    orders,
    signatures: orders.map((_, i) => tree.getEncodedProofAndSignature(i, compact)),
  }
}

;(async () => {
  const cases = []
  for (const n of [1, 2, 3, 4, 50]) cases.push(await makeCase(n))
  const out = {
    _about: `Generated by Seaport.js ${seaportjsVersion} (bulk order tree), bulk listing v2 phase 2. Signer key = ethers id(keyPhrase); test only, never funded.`,
    keyPhrase: KEY_PHRASE,
    signer: wallet.address,
    chainId: CHAIN_ID,
    seaport: SEAPORT,
    cases,
  }
  fs.writeFileSync(outFile, JSON.stringify(out, null, 2) + '\n')
  console.log('wrote', outFile, cases.map((c) => `${c.count}:h${c.height}`).join(' '), 'signer', wallet.address)
})()
